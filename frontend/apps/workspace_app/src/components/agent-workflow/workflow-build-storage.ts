import { pageWorkflowId } from '@/components/agent-workflow/page-workflow-id'
import type { Diagram, DiagramDocument } from '@/components/designer/diagram-types'
import type { PaletteItem } from '@/types/config'
import type { WorkflowBuildSaveResult, WorkflowModelConfig } from '@/types/workflow-build-spec'
import type { WorkflowV4Document } from '@/types/workflow-v4'
import { buildWorkflowV4 } from '@/components/agent-workflow/build-workflow-v4'
import { getGenerationSpec } from '@/services/workflow-generation-spec-api'
import { buildOrchestrationDocument } from '@/components/agent-workflow/build-orchestration-document'
import { saveOrchestration } from '@/services/orchestration-api'
import { getSession } from '@/services/project-auth-store'
import { createWorkflowId } from '@/components/agent-workflow/agent-workflow-defaults'

const WORKSPACE_ID_KEY = 'eleven-nodes-workspace-id'
const BUILD_INDEX_KEY = 'eleven-nodes-workflow-build-index'

export function buildSpecStorageKey(workspaceId: string, pageId: string): string {
  return `eleven-nodes-workflow-build:${workspaceId}:${pageId}`
}

/** Stable workspace id for namespacing build artifacts on this browser. */
export function getOrCreateWorkspaceId(): string {
  try {
    const existing = localStorage.getItem(WORKSPACE_ID_KEY)
    if (existing) return existing
    const created = `ws_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 8)}`
    localStorage.setItem(WORKSPACE_ID_KEY, created)
    return created
  } catch {
    return `ws_local_${createWorkflowId()}`
  }
}

export function ensureDocumentWorkspaceId(doc: DiagramDocument): DiagramDocument {
  if (doc.workspaceId) return doc
  return { ...doc, workspaceId: getOrCreateWorkspaceId() }
}

function updateBuildIndex(entry: WorkflowBuildSaveResult): void {
  try {
    const raw = localStorage.getItem(BUILD_INDEX_KEY)
    const index: WorkflowBuildSaveResult[] = raw ? JSON.parse(raw) : []
    const next = [
      entry,
      ...index.filter(
        (item) =>
          !(item.workspaceId === entry.workspaceId && item.pageId === entry.pageId),
      ),
    ].slice(0, 50)
    localStorage.setItem(BUILD_INDEX_KEY, JSON.stringify(next))
  } catch {
    // quota / private mode
  }
}

export function loadWorkflowBuildSpec(
  workspaceId: string,
  pageId: string,
): WorkflowV4Document | null {
  try {
    const raw = localStorage.getItem(buildSpecStorageKey(workspaceId, pageId))
    if (!raw) return null
    return JSON.parse(raw) as WorkflowV4Document
  } catch {
    return null
  }
}

export function listWorkflowBuildIndex(): WorkflowBuildSaveResult[] {
  try {
    const raw = localStorage.getItem(BUILD_INDEX_KEY)
    return raw ? (JSON.parse(raw) as WorkflowBuildSaveResult[]) : []
  } catch {
    return []
  }
}

interface PersistWorkflowBuildOptions {
  doc: DiagramDocument
  pageId: string
  diagram: Diagram
  /** Kept for callers; the 4.0 document is built from the canvas and the generation spec. */
  paletteById?: Map<string, PaletteItem>
  syncToDisk?: boolean
  requireApi?: boolean
  serverModelConfig?: WorkflowModelConfig
}

/** Build the workflow (format 4.0), cache it locally, and save it to the database when `syncToDisk`. */
export async function persistWorkflowBuildSpec({
  doc,
  pageId,
  diagram,
  syncToDisk = false,
  requireApi = false,
  serverModelConfig,
}: PersistWorkflowBuildOptions): Promise<WorkflowBuildSaveResult> {
  const withWorkspace = ensureDocumentWorkspaceId(doc)
  const workspaceId = withWorkspace.workspaceId!
  const workflowId = pageWorkflowId(withWorkspace, pageId)

  // Workflow format 4.0, generated by the published generation spec: what runs, and the Code tab's JSON
  const generation = await getGenerationSpec()
  const definition = buildWorkflowV4({ doc: withWorkspace, pageId, diagram, spec: generation.document, serverModelConfig })
  const localStorageKey = buildSpecStorageKey(workspaceId, pageId)
  const savedAt = definition.meta.updatedAt

  try {
    localStorage.setItem(localStorageKey, JSON.stringify(definition, null, 2))
  } catch {
    // quota
  }

  const result: WorkflowBuildSaveResult = {
    workspaceId,
    pageId,
    workflowId,
    localStorageKey,
    savedAt,
  }

  if (syncToDisk) {
    try {
      const session = getSession()
      if (!session) throw new Error('Sign in before saving the workflow.')
      // One row per workflow id: the canvas the execute pipeline runs and the Code tab's workflow JSON.
      const apiResult = await saveOrchestration({
        identity: { workflowId, workspaceId: session.workspaceId, tabId: pageId, userId: session.accountId },
        name: definition.meta.name,
        description: definition.meta.description,
        document: buildOrchestrationDocument({
          doc: withWorkspace,
          pageId,
          diagram,
          workspaceId: session.workspaceId,
          userId: session.accountId,
        }),
        definition: definition as unknown as Record<string, unknown>,
      })
      result.databaseRecordId = apiResult.id
    } catch (error) {
      result.databaseError = error instanceof Error ? error.message : String(error)
      if (requireApi) throw error
    }
  }

  updateBuildIndex(result)
  return result
}
